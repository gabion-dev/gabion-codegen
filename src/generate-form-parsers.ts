// src/generate-form-parsers.ts
/**
 * Generate typed parse AND submit functions for *Request Zod schemas.
 *
 * Produces TWO files per generation:
 *   - form-parsers.d.ts — clean type declarations (no Zod references)
 *   - form-parsers.js   — runtime implementation (imports Zod schemas)
 *
 * This .d.ts + .js pair creates a TRUE type boundary:
 *   - TypeScript + @typescript-eslint resolve types from .d.ts → clean,
 *     no Zod internals, no "error typed" propagation
 *   - esbuild resolves runtime code from .js → Zod safeParse() works
 *
 * Two function types are generated:
 *   - parse*Request(data) — validate only, return FormParseResult<T>
 *   - submit*Request(data) — validate + fetch with X-Validated-By header,
 *     return FormSubmitResult<T>. Endpoint info from OpenAPI spec.
 *
 * Submit functions add the X-Validated-By: zod header automatically.
 * The server-side ValidationBypassInterceptor checks for this header —
 * if absent on a JSON request to a @Valid endpoint, it logs a warning.
 * Together they form a two-level defense: submit function prevents bypass
 * by convenience, interceptor detects bypass when prevention fails.
 *
 * Pipeline position: after Hey API + Status Unions, before Frontend Build.
 * Invoked as an npm script of the frontend (working directory =
 * frontend/); the development runtime runs the same script by name.
 */

import {
  readFileSync,
  writeFileSync,
  existsSync,
  unlinkSync,
} from "fs";
import { join } from "path";

import { resolveGeneratorPaths } from "./paths.js";

// ==========================================
// Constants
// ==========================================

const DTS_HEADER = [
  "// This file is auto-generated by generate-form-parsers.ts",
  "// Do not edit manually - changes will be overwritten",
  "//",
  "// Type declarations for form parse and submit functions.",
  "// Clean types only — no Zod references. This is the type boundary",
  "// that @typescript-eslint reads. Runtime lives in form-parsers.js.",
].join("\n");

const JS_HEADER = [
  "// This file is auto-generated by generate-form-parsers.ts",
  "// Do not edit manually - changes will be overwritten",
  "//",
  "// Runtime implementation of form parse and submit functions.",
  "// Imports Zod schemas and calls safeParse(). Submit functions add",
  "// X-Validated-By header for server-side bypass detection.",
  "// Type information is provided by form-parsers.d.ts (the .d.ts + .js boundary).",
].join("\n");

/** Header added by submit functions — checked by ValidationBypassInterceptor. */
const VALIDATED_HEADER_NAME = "X-Validated-By";
const VALIDATED_HEADER_VALUE = "zod";

// ==========================================
// Types
// ==========================================

interface RequestSchemaInfo {
  /** Zod export name, e.g. "zDemoFormRequest" */
  readonly zodExportName: string;

  /** TypeScript type name, e.g. "DemoFormRequest" */
  readonly typeName: string;

  /** Generated parse function name, e.g. "parseDemoFormRequest" */
  readonly parseFunctionName: string;

  /** Generated submit function name, e.g. "submitDemoFormRequest" */
  readonly submitFunctionName: string;
}

interface EndpointInfo {
  /** URL path, e.g. "/api/showcase/demo-form" */
  readonly path: string;

  /** HTTP method uppercase, e.g. "POST" */
  readonly method: string;

  /** Request schema name from OpenAPI, e.g. "DemoFormRequest" */
  readonly requestSchemaName: string;

  /** Response schema name from OpenAPI, or null if no typed response */
  readonly responseSchemaName: string | null;
}

// ==========================================
// Discovery — Zod Schemas
// ==========================================

/**
 * Find all z*Request exports in zod.gen.ts that have a matching
 * type in types.gen.ts.
 *
 * Pattern: `export const z<Name>Request = ...` in zod.gen.ts
 * matched with `export type <Name>Request = ...` in types.gen.ts.
 *
 * Excludes data-envelope schemas like zSubmitDemoFormData
 * (these end with "Data", not "Request").
 */
function discoverRequestSchemas(
  zodContent: string,
  typesContent: string,
): readonly RequestSchemaInfo[] {
  const zodPattern = /export\s+const\s+(z(\w+Request))\s*=/g;
  const schemas: RequestSchemaInfo[] = [];

  let match: RegExpExecArray | null;

  while ((match = zodPattern.exec(zodContent)) !== null) {
    const zodExportName = match[1];
    const typeName = match[2];

    if (zodExportName === undefined || typeName === undefined) {
      continue;
    }

    // Verify corresponding type exists in types.gen.ts
    const typePattern = new RegExp(
      `export\\s+type\\s+${typeName}\\s*=`,
    );

    if (!typePattern.test(typesContent)) {
      continue;
    }

    schemas.push({
      zodExportName,
      typeName,
      parseFunctionName: `parse${typeName}`,
      submitFunctionName: `submit${typeName}`,
    });
  }

  return schemas;
}

// ==========================================
// Discovery — OpenAPI Endpoints
// ==========================================

/**
 * Extract schema name from OpenAPI $ref string.
 * Pattern: "#/components/schemas/SchemaName" → "SchemaName"
 */
function extractSchemaName(ref: string): string | null {
  const match = /^#\/components\/schemas\/(.+)$/.exec(ref);
  return match?.[1] ?? null;
}

/**
 * Find endpoints that use *Request schemas as request body.
 * Returns endpoint info for submit function generation.
 *
 * Only processes application/json request bodies.
 * Response type is extracted from 200 response if available.
 */
function discoverEndpoints(
  openapiContent: string,
  typesContent: string,
): readonly EndpointInfo[] {
  let spec: Record<string, unknown>;
  try {
    spec = JSON.parse(openapiContent) as Record<string, unknown>;
  } catch {
    return [];
  }

  const paths = spec["paths"] as Record<string, Record<string, unknown>> | undefined;
  if (!paths) return [];

  const endpoints: EndpointInfo[] = [];
  const httpMethods = new Set(["get", "post", "put", "patch", "delete"]);

  for (const [path, pathItem] of Object.entries(paths)) {
    for (const [method, operation] of Object.entries(pathItem)) {
      if (!httpMethods.has(method)) continue;

      const op = operation as Record<string, unknown>;

      // Extract request body schema
      const requestBody = op["requestBody"] as Record<string, unknown> | undefined;
      if (!requestBody) continue;

      const requestContent = requestBody["content"] as Record<string, unknown> | undefined;
      if (!requestContent) continue;

      const jsonContent = requestContent["application/json"] as Record<string, unknown> | undefined;
      if (!jsonContent) continue;

      const requestSchema = jsonContent["schema"] as Record<string, string> | undefined;
      const requestRef = requestSchema?.["$ref"];
      if (!requestRef) continue;

      const requestSchemaName = extractSchemaName(requestRef);
      if (!requestSchemaName || !requestSchemaName.endsWith("Request")) continue;

      // Extract response schema (200 response, application/json)
      const responses = op["responses"] as Record<string, unknown> | undefined;
      const okResponse = responses?.["200"] as Record<string, unknown> | undefined;
      const responseContent = okResponse?.["content"] as Record<string, unknown> | undefined;
      const responseJson = responseContent?.["application/json"] as Record<string, unknown> | undefined;
      const responseSchema = responseJson?.["schema"] as Record<string, string> | undefined;
      const responseRef = responseSchema?.["$ref"];

      let responseSchemaName = responseRef ? extractSchemaName(responseRef) : null;

      // Verify response type exists in types.gen.ts
      if (responseSchemaName !== null) {
        const typePattern = new RegExp(
          `export\\s+type\\s+${responseSchemaName}\\s*=`,
        );
        if (!typePattern.test(typesContent)) {
          responseSchemaName = null;
        }
      }

      endpoints.push({
        path,
        method: method.toUpperCase(),
        requestSchemaName,
        responseSchemaName,
      });
    }
  }

  return endpoints;
}

/**
 * Match discovered schemas to their endpoints.
 * Returns a Map: schema type name → endpoint info.
 * Skips schemas used by multiple endpoints (ambiguous).
 */
function matchSchemasToEndpoints(
  schemas: readonly RequestSchemaInfo[],
  endpoints: readonly EndpointInfo[],
): Map<string, EndpointInfo> {
  const schemaNames = new Set(schemas.map((s) => s.typeName));
  const matches = new Map<string, EndpointInfo[]>();

  for (const endpoint of endpoints) {
    if (!schemaNames.has(endpoint.requestSchemaName)) continue;

    const existing = matches.get(endpoint.requestSchemaName);
    if (existing !== undefined) {
      existing.push(endpoint);
    } else {
      matches.set(endpoint.requestSchemaName, [endpoint]);
    }
  }

  const result = new Map<string, EndpointInfo>();

  for (const [schemaName, endpointList] of matches) {
    // Skip ambiguous: schema used by multiple endpoints
    if (endpointList.length === 1 && endpointList[0] !== undefined) {
      result.set(schemaName, endpointList[0]);
    }
  }

  return result;
}

// ==========================================
// Code Generation — Declaration (.d.ts)
// ==========================================

/**
 * Generate form-parsers.d.ts content.
 *
 * Contains ONLY clean type signatures — no Zod imports.
 * This is what TypeScript and @typescript-eslint read for type resolution.
 *
 * Includes:
 *   - FormParseResult types (for parse functions)
 *   - FormSubmitResult types (for submit functions)
 *   - parse*Request() declarations
 *   - submit*Request() declarations (when OpenAPI endpoint found)
 */
function generateDeclaration(
  schemas: readonly RequestSchemaInfo[],
  endpointMap: Map<string, EndpointInfo>,
): string {
  // Collect all type imports: request types + response types
  const typeImports = new Set<string>();
  for (const s of schemas) {
    typeImports.add(s.typeName);
  }
  for (const [, endpoint] of endpointMap) {
    if (endpoint.responseSchemaName !== null) {
      typeImports.add(endpoint.responseSchemaName);
    }
  }

  const lines: string[] = [
    DTS_HEADER,
    "",
    `import type { ${Array.from(typeImports).sort().join(", ")} } from './hey-api/types.gen';`,
    "",
    "// ==========================================",
    "// Parse Result Types",
    "// ==========================================",
    "",
    "export interface FormParseIssue {",
    "  readonly path: readonly PropertyKey[];",
    "  readonly message: string;",
    "}",
    "",
    "export interface FormParseError {",
    "  readonly issues: readonly FormParseIssue[];",
    "}",
    "",
    "interface FormParseSuccess<T> {",
    "  readonly success: true;",
    "  readonly data: T;",
    "}",
    "",
    "interface FormParseFailure {",
    "  readonly success: false;",
    "  readonly error: FormParseError;",
    "}",
    "",
    "export type FormParseResult<T> = FormParseSuccess<T> | FormParseFailure;",
    "",
    "// ==========================================",
    "// Submit Result Types",
    "// ==========================================",
    "",
    "export interface FormSubmitSuccess<T> {",
    "  readonly success: true;",
    "  readonly status: number;",
    "  readonly data: T;",
    "}",
    "",
    "export interface FormSubmitValidationFailure {",
    "  readonly success: false;",
    "  readonly type: 'validation';",
    "  readonly error: FormParseError;",
    "}",
    "",
    "export interface FormSubmitServerFailure {",
    "  readonly success: false;",
    "  readonly type: 'server';",
    "  readonly status: number;",
    "  readonly body: unknown;",
    "}",
    "",
    "export interface FormSubmitNetworkFailure {",
    "  readonly success: false;",
    "  readonly type: 'network';",
    "  readonly message: string;",
    "}",
    "",
    "export type FormSubmitResult<T> =",
    "  | FormSubmitSuccess<T>",
    "  | FormSubmitValidationFailure",
    "  | FormSubmitServerFailure",
    "  | FormSubmitNetworkFailure;",
    "",
    "// ==========================================",
    "// Parse Functions",
    "// ==========================================",
    "",
  ];

  for (const schema of schemas) {
    lines.push(
      `export declare function ${schema.parseFunctionName}(data: unknown): FormParseResult<${schema.typeName}>;`,
      "",
    );
  }

  // Submit functions — only for schemas with matched endpoints
  const hasSubmitFunctions = schemas.some((s) => endpointMap.has(s.typeName));

  if (hasSubmitFunctions) {
    lines.push(
      "// ==========================================",
      "// Submit Functions",
      "// ==========================================",
      "//",
      "// Atomically validate with Zod + send to server with X-Validated-By header.",
      "// Server-side ValidationBypassInterceptor checks for this header.",
      "",
    );

    for (const schema of schemas) {
      const endpoint = endpointMap.get(schema.typeName);
      if (endpoint === undefined) continue;

      const responseType = endpoint.responseSchemaName ?? "unknown";
      lines.push(
        `export declare function ${schema.submitFunctionName}(data: unknown): Promise<FormSubmitResult<${responseType}>>;`,
        "",
      );
    }
  }

  return lines.join("\n");
}

// ==========================================
// Code Generation — Implementation (.js)
// ==========================================

/**
 * Generate form-parsers.js content.
 *
 * Contains runtime code that imports Zod schemas and calls safeParse().
 * Submit functions add X-Validated-By header and CSRF token, then handle
 * the fetch lifecycle.
 *
 * CSRF token is read inline from the XSRF-TOKEN cookie set by Spring
 * Security (csrf.spa()). This duplicates the logic from
 * infrastructure/api/csrf-middleware.ts, but generated/ cannot import
 * from infrastructure/ (architectural boundary). The duplication is
 * acceptable: both read the same cookie with the same pattern, and
 * the generated code is auto-maintained by this generator.
 *
 * The .map() on issues creates an explicit data boundary:
 * consumers receive plain objects matching FormParseIssue,
 * not Zod internal issue instances.
 */
function generateImplementation(
  schemas: readonly RequestSchemaInfo[],
  endpointMap: Map<string, EndpointInfo>,
): string {
  const zodImports = schemas.map((s) => s.zodExportName).join(", ");

  const lines: string[] = [
    JS_HEADER,
    "",
    `import { ${zodImports} } from './hey-api/zod.gen';`,
    "",
    "// ==========================================",
    "// CSRF Token",
    "// ==========================================",
    "",
    "const CSRF_COOKIE = 'XSRF-TOKEN';",
    "const CSRF_HEADER = 'X-XSRF-TOKEN';",
    "",
    "// The one-time submission key the server renders into every form as the",
    "// hidden field _submission (next to the CSRF field). Sent back as the",
    "// Idempotency-Key header so a repeated submit never performs the action",
    "// twice; the server replays the first answer instead.",
    "const SUBMISSION_FIELD = '_submission';",
    "const IDEMPOTENCY_HEADER = 'Idempotency-Key';",
    "",
    "/**",
    " * Read CSRF token from cookie set by Spring Security.",
    " * Duplicates infrastructure/api/csrf-middleware.ts logic —",
    " * generated/ cannot import from infrastructure/ (boundary).",
    " */",
    "function getCsrfToken() {",
    "  const match = document.cookie.match(",
    "    new RegExp('(?:^|;\\\\s*)' + CSRF_COOKIE + '=([^;]*)')",
    "  );",
    "  if (match === null) return null;",
    "  const value = match[1];",
    "  return value !== undefined ? decodeURIComponent(value) : null;",
    "}",
    "",
    "/**",
    " * The submission key carried by the form data, if the data came from a",
    " * rendered form. Zod strips the field from the validated body; the key",
    " * travels in a header instead.",
    " */",
    "function submissionKeyOf(data) {",
    "  if (typeof data !== 'object' || data === null) return null;",
    "  const key = data[SUBMISSION_FIELD];",
    "  return typeof key === 'string' && key !== '' ? key : null;",
    "}",
    "",
    "/**",
    " * Build headers for submit functions.",
    " * Includes Content-Type, X-Validated-By (bypass detection),",
    " * X-XSRF-TOKEN (Spring Security CSRF protection) and, when the data",
    " * carries one, the Idempotency-Key of the form.",
    " */",
    "function buildSubmitHeaders(submissionKey) {",
    "  const headers = {",
    `    'Content-Type': 'application/json',`,
    `    '${VALIDATED_HEADER_NAME}': '${VALIDATED_HEADER_VALUE}',`,
    "  };",
    "  const csrf = getCsrfToken();",
    "  if (csrf !== null) {",
    "    headers[CSRF_HEADER] = csrf;",
    "  }",
    "  if (submissionKey !== null) {",
    "    headers[IDEMPOTENCY_HEADER] = submissionKey;",
    "  }",
    "  return headers;",
    "}",
    "",
    "// ==========================================",
    "// Parse Functions",
    "// ==========================================",
    "",
  ];

  for (const schema of schemas) {
    lines.push(
      `export function ${schema.parseFunctionName}(data) {`,
      `  const result = ${schema.zodExportName}.safeParse(data);`,
      "",
      "  if (result.success) {",
      "    return { success: true, data: result.data };",
      "  }",
      "",
      "  return {",
      "    success: false,",
      "    error: {",
      "      issues: result.error.issues.map((issue) => ({",
      "        path: issue.path,",
      "        message: issue.message,",
      "      })),",
      "    },",
      "  };",
      "}",
      "",
    );
  }

  // Submit functions — only for schemas with matched endpoints
  const hasSubmitFunctions = schemas.some((s) => endpointMap.has(s.typeName));

  if (hasSubmitFunctions) {
    lines.push(
      "// ==========================================",
      "// Submit Functions",
      "// ==========================================",
      "",
    );

    for (const schema of schemas) {
      const endpoint = endpointMap.get(schema.typeName);
      if (endpoint === undefined) continue;

      lines.push(
        `export async function ${schema.submitFunctionName}(data) {`,
        `  const parsed = ${schema.parseFunctionName}(data);`,
        "",
        "  if (!parsed.success) {",
        "    return { success: false, type: 'validation', error: parsed.error };",
        "  }",
        "",
        "  try {",
        `    const response = await fetch('${endpoint.path}', {`,
        `      method: '${endpoint.method}',`,
        "      headers: buildSubmitHeaders(submissionKeyOf(data)),",
        "      body: JSON.stringify(parsed.data),",
        "    });",
        "",
        "    if (response.ok) {",
        "      let responseData;",
        "      try {",
        "        responseData = await response.json();",
        "      } catch {",
        "        responseData = null;",
        "      }",
        "      return { success: true, status: response.status, data: responseData };",
        "    }",
        "",
        "    let body;",
        "    try {",
        "      body = await response.json();",
        "    } catch {",
        "      body = null;",
        "    }",
        "    return { success: false, type: 'server', status: response.status, body };",
        "  } catch (err) {",
        "    const message = err instanceof Error ? err.message : String(err);",
        "    return { success: false, type: 'network', message };",
        "  }",
        "}",
        "",
      );
    }
  }

  return lines.join("\n");
}

// ==========================================
// File Writing with Idempotency
// ==========================================

/**
 * Write content to file only if changed. Returns true if written.
 */
function writeIfChanged(filePath: string, content: string): boolean {
  if (existsSync(filePath)) {
    const existing = readFileSync(filePath, "utf-8");
    if (existing === content) {
      return false;
    }
  }

  writeFileSync(filePath, content);
  return true;
}

// ==========================================
// Public API
// ==========================================

/**
 * Generate form-parsers.d.ts + form-parsers.js with typed parse and submit
 * functions for all *Request Zod schemas.
 *
 * Parse functions: validate data with Zod, return FormParseResult<T>.
 * Submit functions: validate + fetch with X-Validated-By header,
 *   return FormSubmitResult<T>. Requires OpenAPI spec for endpoint info.
 *
 * The .d.ts + .js pair is a standard npm-style type boundary:
 * - TypeScript / @typescript-eslint read .d.ts (clean types, no Zod)
 * - esbuild reads .js (runtime with Zod safeParse + fetch)
 *
 * Idempotent: returns false if output is unchanged.
 * Handles missing input files gracefully (first run before Hey API).
 * Submit functions require openapi.json — if absent, only parse functions
 * are generated (backward compatible with lightweight regen).
 *
 * @param generatedDir - Path to frontend/src/generated/
 * @param openapiPath - Path to openapi.json (optional, computed from convention)
 * @returns true if files were created or changed, false if unchanged
 */
export function generateFormParsers(
  generatedDir: string,
  openapiPath?: string,
): boolean {
  const zodGenPath = join(generatedDir, "hey-api", "zod.gen.ts");
  const typesGenPath = join(generatedDir, "hey-api", "types.gen.ts");
  const dtsPath = join(generatedDir, "form-parsers.d.ts");
  const jsPath = join(generatedDir, "form-parsers.js");

  // Clean up stale .ts file from previous approach (if any)
  const staleTsPath = join(generatedDir, "form-parsers.ts");
  if (existsSync(staleTsPath)) {
    unlinkSync(staleTsPath);
  }

  // Hey API hasn't run yet — nothing to generate from
  if (!existsSync(zodGenPath) || !existsSync(typesGenPath)) {
    return false;
  }

  const zodContent = readFileSync(zodGenPath, "utf-8");
  const typesContent = readFileSync(typesGenPath, "utf-8");

  const schemas = discoverRequestSchemas(zodContent, typesContent);

  if (schemas.length === 0) {
    // No Request schemas — write minimal placeholder
    const emptyDts = DTS_HEADER + "\n\n// No *Request schemas found in zod.gen.ts\n";
    const emptyJs = JS_HEADER + "\n\n// No *Request schemas found in zod.gen.ts\n";

    const dtsChanged = writeIfChanged(dtsPath, emptyDts);
    const jsChanged = writeIfChanged(jsPath, emptyJs);
    return dtsChanged || jsChanged;
  }

  // Discover endpoints from OpenAPI spec for submit functions
  const resolvedOpenapiPath = openapiPath
    ?? resolveGeneratorPaths(join(generatedDir, "..", "..")).openApiSpecPath;

  let endpointMap = new Map<string, EndpointInfo>();

  if (existsSync(resolvedOpenapiPath)) {
    const openapiContent = readFileSync(resolvedOpenapiPath, "utf-8");
    const endpoints = discoverEndpoints(openapiContent, typesContent);
    endpointMap = matchSchemasToEndpoints(schemas, endpoints);
  }

  const dtsContent = generateDeclaration(schemas, endpointMap);
  const jsContent = generateImplementation(schemas, endpointMap);

  const dtsChanged = writeIfChanged(dtsPath, dtsContent);
  const jsChanged = writeIfChanged(jsPath, jsContent);

  return dtsChanged || jsChanged;
}
